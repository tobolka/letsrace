const assert=require('node:assert/strict');
const {health,isDeferredExit}=require('./local-runner.cjs');
const now=Date.now();
assert.equal(health({active:false,paused:false,now,lastExitCode:0}),'waiting');
assert.equal(health({active:true,paused:true,now,lastOutputAt:now}),'running');
assert.equal(health({active:false,paused:true,now,lastExitCode:1}),'paused');
assert.equal(health({active:true,paused:false,now,lastOutputAt:now-21*60_000}),'quiet');
assert.equal(health({active:false,paused:false,now,lastExitCode:2}),'attention');
const deferredFooter='=== done 15:42:31\n=== failed steps: 0\n=== deferred steps: 1\n';
assert.equal(isDeferredExit(2,deferredFooter),true);
assert.equal(isDeferredExit(2,deferredFooter.replace('failed steps: 0','failed steps: 1')),false);
assert.equal(isDeferredExit(2,'shell: syntax error'),false);
assert.equal(health({active:false,paused:false,now,lastExitCode:2,deferredOnly:isDeferredExit(2,deferredFooter)}),'waiting');
assert.equal(health({active:false,paused:false,now,lastExitCode:1}),'attention');
assert.equal(health({active:false,paused:false,now,lastExitCode:143}),'attention');
console.log('PASS: waiting, live work, pause after completion, quiet work and failed runs stay distinct');
const {rememberResult,recentResults}=require('./local-runner.cjs');
const state={};
rememberResult(state,{at:now,reads:4,created:2,updated:1,failed:1,problems:[{url:'https://race.test',error:'timeout'}]});
rememberResult(state,{at:now+1,reads:0,created:0,updated:0,failed:0,problems:[]});
assert.equal(state.lastResult.reads,0);assert.equal(state.lastActivityResult.created,2);
assert.equal(recentResults(state.history,now+2).failed,1);
assert.equal(recentResults(state.history,now+2).problems.length,1);
assert.equal(recentResults(state.history,now+25*60*60_000).reads,0);
console.log('PASS: empty runs preserve earlier activity and 24-hour problems without inventing new writes');

const {normalizeResult}=require('./local-runner.cjs');
assert.deepEqual(normalizeResult({failed:3,problems:[{error:'unsupported_or_empty_source'},{error:'low confidence or empty extract'},{error:'HTTP 503'}]}),{failed:1,unreadable:2,problems:[{error:'unsupported_or_empty_source'},{error:'low confidence or empty extract'},{error:'HTTP 503'}]});
assert.equal(normalizeResult({failed:2,unreadable:1,problems:[{error:'unsupported_or_empty_source'}]}).failed,2);
console.log('PASS: historical diagnostics separate reader limits without hiding unknown failures');

const {managedCommand}=require('./local-runner.cjs');
assert.equal(managedCommand('/runtime'),'/runtime/scripts/local-cycle.sh');
assert.equal(managedCommand('/runtime','/fixture/fake.sh'),'/fixture/fake.sh');
console.log('PASS: managed production command uses the isolated local cycle');
